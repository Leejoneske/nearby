import type { Business, WeekHours } from './types';

const h = (open: number, close: number) => ({ open, close });

/** Same hours Mon–Fri, separate weekend, closed days as null. */
function week(opts: {
  weekday: [number, number] | null;
  sat?: [number, number] | null;
  sun?: [number, number] | null;
}): WeekHours {
  const wd = opts.weekday ? h(opts.weekday[0], opts.weekday[1]) : null;
  const sat = opts.sat === undefined ? opts.weekday : opts.sat;
  const sun = opts.sun === undefined ? opts.weekday : opts.sun;
  return [
    sun ? h(sun[0], sun[1]) : null,
    wd,
    wd,
    wd,
    wd,
    wd,
    sat ? h(sat[0], sat[1]) : null,
  ];
}

